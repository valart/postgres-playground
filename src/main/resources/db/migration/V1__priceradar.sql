CREATE TABLE shops (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL CHECK (length(trim(name)) BETWEEN 1 AND 120)
);

CREATE TABLE products (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL CHECK (length(trim(name)) BETWEEN 1 AND 120)
);

CREATE TABLE offers (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_id bigint NOT NULL REFERENCES shops(id),
    product_id bigint NOT NULL REFERENCES products(id),
    current_price bigint NOT NULL CHECK (current_price >= 0),
    available boolean NOT NULL,
    last_updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT offers_shop_product_key UNIQUE (shop_id, product_id)
);

CREATE TABLE offer_minimum_prices (
    offer_id bigint PRIMARY KEY REFERENCES offers(id) ON DELETE CASCADE,
    min_price bigint NOT NULL CHECK (min_price >= 0)
);
